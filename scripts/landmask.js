// Builds src/detect-land.js, the land mask of @duoquote/polytini/detect/land:
// a grid of cells that have land in them.
//
//   node scripts/landmask.js path/to/ne_110m_land.geojson [--cell 1]
//
// Source: Natural Earth 1:110m land, v5.1.2, public domain
// (https://www.naturalearthdata.com/about/terms-of-use/), from
// https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson
// A cell counts as land when any of 25 sample points in each degree of it
// is on land, so coasts are generous. `--cell` is the cell size in degrees:
// 1 (the default, what the package ships), 2, 3, 4, 5 or 6. docs/api.md has
// what each size costs and buys. Ported from the demo site's
// site/scripts/landmask.mjs.
import { readFileSync, writeFileSync } from 'node:fs';

const args = process.argv.slice(2);
const cell = Number(args.includes('--cell') ? args[args.indexOf('--cell') + 1] : 1);
const geo = JSON.parse(readFileSync(args[0], 'utf8'));
const polys = geo.features.flatMap((f) => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates));
// Each polygon's bounding box, so a point only tests the few it can be in.
const boxes = polys.map((poly) => {
  let w = 180, s = 90, e = -180, n = -90;
  for (const [x, y] of poly[0]) (w = Math.min(w, x)), (e = Math.max(e, x)), (s = Math.min(s, y)), (n = Math.max(n, y));
  return [w, s, e, n];
});
const inRing = (x, y, ring) => {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};
const onLand = (x, y) =>
  polys.some((poly, i) => {
    const [w, s, e, n] = boxes[i];
    return x >= w && x <= e && y >= s && y <= n && inRing(x, y, poly[0]) && !poly.slice(1).some((h) => inRing(x, y, h));
  });

// One degree cells first, 25 sample points each, then `cell` degree cells
// that have land in any of theirs. Row 0 is the band just below latitude
// 90, column 0 starts at longitude -180.
const fine = new Uint8Array(180 * 360);
for (let row = 0; row < 180; row++) {
  for (let col = 0; col < 360; col++) {
    let land = false;
    for (let a = 0; a < 5 && !land; a++) for (let b = 0; b < 5 && !land; b++) land = onLand(-180 + col + (b + 0.5) / 5, 89 - row + (a + 0.5) / 5);
    fine[row * 360 + col] = land ? 1 : 0;
  }
}
const rows = 180 / cell, cols = 360 / cell, bits = new Array(rows * cols).fill(0);
for (let row = 0; row < 180; row++) for (let col = 0; col < 360; col++) if (fine[row * 360 + col]) bits[Math.floor(row / cell) * cols + Math.floor(col / cell)] = 1;
// Run lengths, alternating water and land, starting with water, in base 36.
const runs = [];
let cur = 0, n = 0;
for (const b of bits) {
  if (b === cur) n++;
  else {
    runs.push(n);
    cur = b;
    n = 1;
  }
}
runs.push(n);
const land = bits.filter(Boolean).length;
writeFileSync(
  new URL('../src/detect-land.js', import.meta.url),
  `// Generated by scripts/landmask.js from Natural Earth 1:110m land (public
// domain): ${land} of ${bits.length} cells of ${cell} by ${cell} degrees have land in them.
// Don't edit by hand.
/* @ts-self-types="../types/detect-land.d.ts" */
const RUNS = '${runs.map((r) => r.toString(36)).join(',')}';

let grid;
const load = () => {
  const g = new Uint8Array(${bits.length});
  let i = 0, on = 0;
  for (const r of RUNS.split(',')) {
    const n = parseInt(r, 36);
    if (on) g.fill(1, i, i + n);
    i += n;
    on ^= 1;
  }
  return g;
};

/** Whether the ${cell} by ${cell} degree cell around a point has land in it. False out of range. */
export function isLand(lat, lng) {
  if (!(Math.abs(lat) <= 90 && Math.abs(lng) <= 180)) return false;
  grid ||= load();
  const row = Math.min(${rows - 1}, Math.floor(${cell > 1 ? `(90 - lat) / ${cell}` : '90 - lat'})), col = Math.min(${cols - 1}, Math.floor(${cell > 1 ? `(lng + 180) / ${cell}` : 'lng + 180'}));
  return grid[row * ${cols} + col] == 1;
}
`,
);
console.log(`land cells: ${land} of ${bits.length}, runs: ${runs.length}`);
