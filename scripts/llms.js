// Builds llms-full.txt, the long version of llms.txt for AI agents, from
// files that already exist, so it can't drift from the code:
// - the top of llms.txt (everything before its first "## " section)
// - every import path's module doc and type file (package.json exports,
//   plus the JSR-only /cli), with the doc comments as written
// - docs/api.md, docs/integrations.md and docs/cli.md, one heading level down
//   and with relative links made absolute
//   node scripts/llms.js           write llms-full.txt
//   node scripts/llms.js --check   exit 1 if llms-full.txt is out of date, or
//                                  if llms.txt misses an import path or links
//                                  to a file that doesn't exist
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const read = (path) => readFileSync(new URL(path, root), 'utf8').replace(/\r\n/g, '\n');
const pkg = JSON.parse(read('package.json'));
const jsr = JSON.parse(read('jsr.json'));
const blob = 'https://github.com/Duoquote/polytini/blob/main/';
const raw = 'https://raw.githubusercontent.com/Duoquote/polytini/main/';
const guides = ['docs/api.md', 'docs/integrations.md', 'docs/cli.md'];

// The /** ... @module */ block of a type file, as Markdown.
function moduleDoc(src) {
  const block = src.match(/\/\*\*((?:(?!\*\/)[\s\S])*?@module(?:(?!\*\/)[\s\S])*?)\*\//);
  if (!block) return { doc: '', rest: src };
  const doc = block[1]
    .split('\n')
    .map((l) => l.replace(/^\s*\* ?/, ''))
    .filter((l) => !/^@module\b/.test(l.trim()))
    .join('\n')
    .trim();
  return { doc, rest: src.replace(block[0], '') };
}

// The file a src/*.js entry gets its types from on JSR.
const selfTypes = (file) => {
  const m = read(file.replace(/^\.\//, '')).match(/@ts-self-types="([^"]+)"/);
  return m && new URL(m[1], new URL(file, root)).href.slice(root.href.length);
};

// One group per npm type file, in package.json order, so the four entries
// that share types/index.d.ts get one section.
const groups = new Map();
const add = (key, types, jsrOnly = false) => {
  const g = groups.get(types) ?? groups.set(types, { paths: [], types, jsr: [], jsrOnly }).get(types);
  g.paths.push(pkg.name + key.slice(1));
  if (jsr.exports[key]) g.jsr.push(jsr.exports[key]);
};
for (const [key, value] of Object.entries(pkg.exports)) {
  if (key === './package.json') continue;
  const types = typeof value === 'string' ? null : (value.types ?? pkg.types).replace(/^\.\//, '');
  add(key, types ?? key);
}
for (const [key, file] of Object.entries(jsr.exports)) {
  if (!(key in pkg.exports)) add(key, selfTypes(file), true);
}

function reference() {
  let out = '## API reference by import path\n\n';
  out += `Generated from the type files in \`types/\`. The npm package ships them, so they're also in \`node_modules/${pkg.name}/types/\`.\n`;
  for (const g of groups.values()) {
    out += `\n### ${g.paths.map((p) => `\`${p}\``).join(', ')}\n\n`;
    if (!g.types.endsWith('.d.ts')) {
      out += `The WebAssembly module as a file, for \`init(module)\` from \`${pkg.name}/wasm\` where the runtime can't compile WebAssembly from bytes, like Cloudflare Workers. npm only; the JSR package doesn't include it.\n`;
      continue;
    }
    const jsrTypes = [...new Set(g.jsr.map(selfTypes))];
    // The module doc JSR shows; the npm type file has the same text, or none.
    const fromJsr = jsrTypes[0] ? moduleDoc(read(jsrTypes[0])).doc : '';
    const { doc, rest } = moduleDoc(read(g.types));
    if (fromJsr || doc) out += `${fromJsr || doc}\n\n`;
    if (g.jsrOnly) out += 'JSR only. On npm, the same command is the `polytini` bin.\n\n';
    const other = jsrTypes.filter((t) => t !== g.types);
    if (other.length) out += `On JSR this entry is typed by \`${other.join('`, `')}\`, a copy with structural types, because JSR builds its docs without node_modules.\n\n`;
    out += `\`${g.types}\`:\n\n\`\`\`ts\n${rest.replace(/\n{3,}/g, '\n\n').trim()}\n\`\`\`\n`;
  }
  return out;
}

// A docs/ file one heading level down, with relative links made absolute.
function guide(path) {
  let fence = false;
  return read(path)
    .split('\n')
    .map((line) => {
      if (/^\s*```/.test(line)) fence = !fence;
      if (fence) return line;
      if (/^#{1,5} /.test(line)) line = '#' + line;
      return line.replace(/\]\((?!https?:|#|mailto:)([^)\s]+)\)/g, (_, link) => `](${new URL(link, blob + path).href})`);
    })
    .join('\n')
    .trim();
}

function build() {
  const llms = read('llms.txt');
  const intro = llms.slice(0, llms.search(/^## /m)).trim();
  return [
    intro.replace(/^(# .+)\n/, `$1\n\n<!-- Generated by scripts/llms.js from llms.txt, types/*.d.ts and ${guides.join(', ')}. Don't edit by hand: run node scripts/llms.js. -->\n`),
    reference().trim(),
    ...guides.map(guide),
  ].join('\n\n') + '\n';
}

// llms.txt is written by hand. Check that it names every import path and
// that its links to this repo's files point at files that exist.
function checkLlms() {
  const llms = read('llms.txt');
  const problems = [];
  for (const key of new Set([...Object.keys(pkg.exports), ...Object.keys(jsr.exports)])) {
    if (key === './package.json') continue;
    const sub = key.slice(1);
    if (!llms.includes(`${pkg.name}${sub}\``) && !(sub && llms.includes(`${sub}\``))) problems.push(`llms.txt doesn't mention ${pkg.name}${sub}`);
  }
  for (const [, path] of llms.matchAll(/\]\(https:\/\/raw\.githubusercontent\.com\/Duoquote\/polytini\/main\/([^)#]+)\)/g)) {
    if (!existsSync(new URL(path, root))) problems.push(`llms.txt links to ${raw}${path}, which isn't in the repo`);
  }
  return problems;
}

const next = build();
if (process.argv.includes('--check')) {
  const problems = checkLlms();
  const current = existsSync(new URL('llms-full.txt', root)) ? read('llms-full.txt') : '';
  if (current !== next) problems.push('llms-full.txt is out of date: run node scripts/llms.js and commit the result');
  if (problems.length) {
    console.error(problems.join('\n'));
    process.exit(1);
  }
  console.log(`llms-full.txt is up to date (${next.length} bytes), and llms.txt names every import path`);
} else {
  writeFileSync(new URL('llms-full.txt', root), next);
  console.log(`wrote llms-full.txt (${next.length} bytes)`);
}
