// Assembles the two WASM modules and inlines both as hex in
// src/wasm-bytes.js, so the /wasm entry needs no fetch or fs.
//   node scripts/build-wasm.js
// - wasm/polytini.wat, with wabt: the module every runtime can use.
// - wasm/polytini-strings.wat, with binaryen, because wabt can't assemble
//   Wasm GC arrays: the same loops on JS String Builtins (wasm:js-string),
//   used where the runtime has them (src/wasm.js says where).
// CI runs this and fails if the committed files differ from the result.
import { readFileSync, writeFileSync } from 'node:fs';
import wabt from 'wabt';
import binaryen from 'binaryen';

const dir = new URL('../', import.meta.url);
const read = (f) => readFileSync(new URL(f, dir), 'utf8');

const w = await wabt();
const mod = w.parseWat('polytini.wat', read('wasm/polytini.wat'));
mod.resolveNames();
mod.validate();
const { buffer } = mod.toBinary({ write_debug_names: false });
mod.destroy();

const m = binaryen.parseText(read('wasm/polytini-strings.wat'));
// An explicit list, so CompactImports stays off: with binaryen's compact
// import encoding, no engine accepted the module.
const F = binaryen.Features;
m.setFeatures(F.MutableGlobals | F.NontrappingFPToInt | F.BulkMemory | F.SignExt | F.ReferenceTypes | F.Multivalue | F.GC);
if (!m.validate()) throw new Error('wasm/polytini-strings.wat is not valid');
const strings = m.emitBinary();
m.dispose();

writeFileSync(new URL('wasm/polytini.wasm', dir), buffer);
writeFileSync(new URL('wasm/polytini-strings.wasm', dir), strings);
const hex = (b) => Buffer.from(b).toString('hex');
writeFileSync(
  new URL('src/wasm-bytes.js', dir),
  `// Generated by scripts/build-wasm.js from wasm/polytini.wat and wasm/polytini-strings.wat. Do not edit.\nexport default '${hex(buffer)}';\nexport const strings = '${hex(strings)}';\n`,
);
console.log(`wasm/polytini.wasm: ${buffer.length} bytes, wasm/polytini-strings.wasm: ${strings.length} bytes`);
